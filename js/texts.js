export function plural(n, one, few, many) {
  const a = Math.abs(n) % 100;
  const b = a % 10;
  if (a > 10 && a < 20) return many;
  if (b > 1 && b < 5) return few;
  if (b === 1) return one;
  return many;
}

const WORDS_1 = ["ноль", "одно", "два", "три", "четыре", "пять", "шесть", "семь",
  "восемь", "девять", "десять", "одиннадцать", "двенадцать", "тринадцать",
  "четырнадцать", "пятнадцать", "шестнадцать", "семнадцать", "восемнадцать", "девятнадцать"];
const WORDS_10 = ["", "", "двадцать", "тридцать", "сорок", "пятьдесят",
  "шестьдесят", "семьдесят", "восемьдесят", "девяносто"];

// Число словами. Нужно там, где цифра читается тяжелее слова.
export function inWords(n) {
  n = Math.round(Number(n) || 0);
  if (n < 0) return String(n);
  if (n < 20) return WORDS_1[n];
  if (n < 100) {
    const t = WORDS_10[Math.floor(n / 10)];
    const r = n % 10;
    return r ? t + " " + WORDS_1[r] : t;
  }
  return String(n);
}

